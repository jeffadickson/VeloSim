using System.Globalization;
using System.Text;
using System.Text.Json;

namespace VeloSim;

public sealed record ClockDomainInfo(
    string ClockSignal,
    bool IsPrimaryInput,
    bool IsConstrainedInSdc,
    IReadOnlyList<string> Signals);

public sealed record CdcCrossingInfo(
    string Kind,
    string SourceSignal,
    string SourceDomain,
    string DestinationSignal,
    string DestinationDomain,
    int Width,
    bool Synchronized,
    int SynchronizerStages,
    bool FalsePath,
    string Context);

public sealed record CdcAnalysisResult(
    IReadOnlyList<ClockDomainInfo> ClockDomains,
    IReadOnlyList<string> ResetSignals,
    IReadOnlyList<CdcCrossingInfo> Crossings,
    IReadOnlyList<LintDiagnostic> Diagnostics)
{
    public static CdcAnalysisResult Empty { get; } = new([], [], [], []);

    /// <summary>
    /// Generates IEEE 1800 SystemVerilog Assertions (SVA) for all unsynchronized CDC/RDC crossings,
    /// matching Aldec ALINT-PRO's dynamic CDC assertion generation workflow.
    /// </summary>
    public string GenerateSvaAssertions(string moduleName = "velosim_cdc_assertions")
    {
        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by VeloSim Flagship Linter (CDC/RDC SVA assertions)");
        sb.AppendLine($"// Clock domains: {ClockDomains.Count}, Crossings: {Crossings.Count}");
        sb.Append("module ").Append(moduleName).AppendLine("_chk;");
        int idx = 0;
        foreach (var c in Crossings)
        {
            if (c.FalsePath) continue;
            string kindTag = c.Kind.ToLowerInvariant();
            string propName = $"p_{kindTag}_{idx}_{SanitizeId(c.SourceSignal)}_to_{SanitizeId(c.DestinationSignal)}";
            sb.AppendLine(CultureInfo.InvariantCulture, $"  // {c.Kind}: {c.SourceSignal} ({c.SourceDomain}, {c.Width}-bit) -> {c.DestinationSignal} ({c.DestinationDomain}) [sync={c.Synchronized}, stages={c.SynchronizerStages}]");
            if (c.Kind == "CDC")
            {
                sb.AppendLine($"  property {propName};");
                sb.AppendLine($"    @(posedge {c.DestinationDomain}) $changed({c.SourceSignal}) |-> $stable({c.SourceSignal});");
                sb.AppendLine("  endproperty");
                sb.AppendLine($"  a_{propName}: assert property ({propName})");
                sb.AppendLine($"    else $error(\"[VELOSIM-CDC] Crossing stability violation: {c.SourceSignal} ({c.SourceDomain}) -> {c.DestinationSignal} ({c.DestinationDomain})\");");
            }
            else
            {
                sb.AppendLine($"  property {propName};");
                sb.AppendLine($"    @(posedge {c.SourceDomain}) $rose({c.SourceDomain}) |-> !$isunknown({c.DestinationSignal});");
                sb.AppendLine("  endproperty");
                sb.AppendLine($"  a_{propName}: assert property ({propName})");
                sb.AppendLine($"    else $error(\"[VELOSIM-RDC] Reset domain crossing violation: {c.SourceSignal} ({c.SourceDomain}) -> {c.DestinationSignal} ({c.DestinationDomain})\");");
            }
            idx++;
        }
        sb.AppendLine("endmodule");
        return sb.ToString();
    }

    private static string SanitizeId(string name)
    {
        var sb = new StringBuilder(name.Length);
        foreach (char c in name)
            sb.Append(char.IsAsciiLetterOrDigit(c) || c == '_' ? c : '_');
        return sb.ToString();
    }
}

/// <summary>
/// Pure C# clock/reset auto-detector, structural CDC/RDC analyzer, 2-FF synchronizer recognizer,
/// DFT clock/reset controllability checker, and SDC constraint auditor (inspired by Aldec ALINT-PRO
/// <c>ALDEC_CDC</c>, Questa CDC/Lint, and VC SpyGlass).
/// </summary>
public static class RtlCdcAnalyzer
{
    private const int MaxDepth = 64;

    private sealed record SeqTransfer(
        string Destination,
        string ClockDomain,
        string? ResetDomain,
        string? DirectSourceRef,
        HashSet<string> AllSourceReads,
        string Context);

    public static CdcAnalysisResult Analyze(
        JsonElement root,
        IReadOnlyDictionary<string, (int Width, string Direction)> signals,
        SdcConstraints? sdc,
        bool hasExplicitSdc,
        string? sourceFile)
    {
        if (root.ValueKind != JsonValueKind.Object)
            return CdcAnalysisResult.Empty;

        var diagnostics = new List<LintDiagnostic>();
        var detectedClocks = new HashSet<string>(StringComparer.Ordinal);
        var detectedResets = new HashSet<string>(StringComparer.Ordinal);
        var asyncResets = new HashSet<string>(StringComparer.Ordinal);
        var transfers = new List<SeqTransfer>();

        string? rootClock = root.TryGetProperty("clock", out var rcEl) && rcEl.ValueKind == JsonValueKind.String ? rcEl.GetString() : null;
        if (!string.IsNullOrEmpty(rootClock))
            detectedClocks.Add(rootClock);

        // 1. Inspect sequential processes in body (and timed event blocks)
        if (root.TryGetProperty("body", out var bodyEl) && bodyEl.ValueKind == JsonValueKind.Object)
        {
            foreach (var (proc, ctx) in EnumerateProcesses(bodyEl))
            {
                string? procClock = rootClock;
                string? procReset = null;

                if (TryString(proc, "kind") == "process" && proc.TryGetProperty("events", out var evs) && evs.ValueKind == JsonValueKind.Array)
                {
                    var evList = new List<string>();
                    foreach (var ev in evs.EnumerateArray())
                        if (TryString(ev, "signal") is { Length: > 0 } es) evList.Add(es);
                    if (evList.Count > 0)
                    {
                        procClock = evList[0];
                        detectedClocks.Add(procClock);
                    }
                    for (int i = 1; i < evList.Count; i++)
                    {
                        procReset = evList[i];
                        detectedResets.Add(procReset);
                        asyncResets.Add(procReset);
                    }
                }

                if (string.IsNullOrEmpty(procClock)) continue;

                JsonElement stmtBody = TryString(proc, "kind") == "process" && proc.TryGetProperty("body", out var pb) ? pb : proc;
                // Detect synchronous reset signal if no async reset was listed
                if (procReset is null)
                {
                    procReset = TryDetectSyncReset(stmtBody);
                    if (procReset is not null) detectedResets.Add(procReset);
                }

                CollectSequentialTransfers(stmtBody, procClock, procReset, ctx, transfers, 0);
            }
        }

        // Also detect clocks/resets from timed event controls for DFT controllability checks
        if (root.TryGetProperty("timed", out var timedEl) && timedEl.ValueKind == JsonValueKind.Array)
        {
            int idx = 0;
            foreach (var tProc in timedEl.EnumerateArray())
                CollectTimedEventClocks(tProc, $"timed[{idx++}]", detectedClocks, asyncResets, 0);
        }

        // 2. DFT Clock & Reset Controllability checks
        foreach (string clk in detectedClocks.Order(StringComparer.Ordinal))
        {
            if (signals.TryGetValue(clk, out var info) && info.Direction != "input")
            {
                diagnostics.Add(new LintDiagnostic(
                    "DFTCLKCTRL",
                    LintSeverity.Warning,
                    $"Clock signal '{clk}' is internally generated/gated ({info.Direction}) rather than directly controllable from a primary input port.",
                    "cdc",
                    new LintLocation(sourceFile, null, null, clk, "dft")));
            }
        }

        foreach (string rst in asyncResets.Order(StringComparer.Ordinal))
        {
            if (signals.TryGetValue(rst, out var info) && info.Direction != "input")
            {
                diagnostics.Add(new LintDiagnostic(
                    "DFTRSTCTRL",
                    LintSeverity.Warning,
                    $"Asynchronous reset signal '{rst}' is internally generated ({info.Direction}) rather than directly controllable from a primary input port.",
                    "cdc",
                    new LintLocation(sourceFile, null, null, rst, "dft")));
            }
        }

        // 3. SDC Constraint Audit (Aldec ALINT-PRO unconstrained / over-constrained clock check)
        var effectiveSdc = sdc ?? SdcConstraints.Empty;
        if (hasExplicitSdc)
        {
            foreach (string clk in detectedClocks.Order(StringComparer.Ordinal))
            {
                if (!effectiveSdc.HasClockTarget(clk))
                {
                    diagnostics.Add(new LintDiagnostic(
                        "SDCUCONSTR",
                        LintSeverity.Warning,
                        $"Clock '{clk}' detected in RTL is unconstrained in the provided SDC file.",
                        "cdc",
                        new LintLocation(sourceFile, null, null, clk, "sdc")));
                }
            }
            foreach (var sdcClk in effectiveSdc.Clocks)
            {
                if (!signals.ContainsKey(sdcClk.TargetSignal) && !detectedClocks.Contains(sdcClk.TargetSignal))
                {
                    diagnostics.Add(new LintDiagnostic(
                        "SDCOVERCONSTR",
                        LintSeverity.Warning,
                        $"Clock '{sdcClk.Name}' (target '{sdcClk.TargetSignal}') in SDC file does not match any signal in RTL.",
                        "cdc",
                        new LintLocation(sourceFile, null, null, sdcClk.TargetSignal, "sdc")));
                }
            }
        }

        // 4. Build owning clock & reset domain maps for sequential flops
        var flopClock = new Dictionary<string, string>(StringComparer.Ordinal);
        var flopReset = new Dictionary<string, string>(StringComparer.Ordinal);
        var domainSignals = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);

        foreach (string clk in detectedClocks)
            domainSignals[clk] = new HashSet<string>(StringComparer.Ordinal);

        foreach (var tr in transfers)
        {
            flopClock.TryAdd(tr.Destination, tr.ClockDomain);
            if (tr.ResetDomain is not null) flopReset.TryAdd(tr.Destination, tr.ResetDomain);
            if (!domainSignals.TryGetValue(tr.ClockDomain, out var set))
            {
                set = new HashSet<string>(StringComparer.Ordinal);
                domainSignals[tr.ClockDomain] = set;
            }
            set.Add(tr.Destination);
        }

        // 5. Propagate domains through combinational/continuous cones (comb_sig -> source flops)
        var combDependencies = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        CollectCombinationalDependencies(root, combDependencies);

        var signalSourceFlops = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        foreach (string f in flopClock.Keys)
            signalSourceFlops[f] = new HashSet<string>(StringComparer.Ordinal) { f };

        for (int iter = 0; iter < 32; iter++)
        {
            bool changed = false;
            foreach (var (dst, reads) in combDependencies)
            {
                if (flopClock.ContainsKey(dst)) continue;
                if (!signalSourceFlops.TryGetValue(dst, out var dstSet))
                {
                    dstSet = new HashSet<string>(StringComparer.Ordinal);
                    signalSourceFlops[dst] = dstSet;
                }
                foreach (string r in reads)
                {
                    if (signalSourceFlops.TryGetValue(r, out var rSet))
                    {
                        foreach (string sf in rSet)
                            if (dstSet.Add(sf)) changed = true;
                    }
                }
            }
            if (!changed) break;
        }

        // 6. Track consumers of each flop (for 2-FF synchronizer chain recognition)
        var flopConsumers = new Dictionary<string, List<SeqTransfer>>(StringComparer.Ordinal);
        foreach (var tr in transfers)
        {
            foreach (string r in tr.AllSourceReads)
            {
                if (!flopConsumers.TryGetValue(r, out var list))
                {
                    list = [];
                    flopConsumers[r] = list;
                }
                list.Add(tr);
            }
        }
        var combReadSignals = new HashSet<string>(combDependencies.Values.SelectMany(v => v), StringComparer.Ordinal);

        // 7. Detect CDC and RDC crossings
        var crossings = new List<CdcCrossingInfo>();
        var seenCrossing = new HashSet<string>(StringComparer.Ordinal);

        foreach (var tr in transfers)
        {
            foreach (string readSig in tr.AllSourceReads)
            {
                // Ignore self-reads and clock/reset control reads
                if (readSig == tr.Destination || detectedClocks.Contains(readSig) || detectedResets.Contains(readSig))
                    continue;

                if (!signalSourceFlops.TryGetValue(readSig, out var launchFlops))
                    continue;

                bool isDirectFlopRead = tr.DirectSourceRef == readSig && flopClock.ContainsKey(readSig);

                foreach (string launch in launchFlops)
                {
                    if (launch == tr.Destination) continue;
                    string launchClk = flopClock[launch];
                    int width = signals.TryGetValue(launch, out var sInfo) ? sInfo.Width : 1;

                    // CDC check: launch clock != capture clock
                    if (!effectiveSdc.AreClocksSynchronous(launchClk, tr.ClockDomain))
                    {
                        string key = $"CDC|{launch}|{launchClk}|{tr.Destination}|{tr.ClockDomain}";
                        if (!seenCrossing.Add(key)) continue;

                        bool isFalsePath = effectiveSdc.IsFalsePath(launch, launchClk, tr.Destination, tr.ClockDomain);
                        int syncStages = isDirectFlopRead && width == 1
                            ? CountSynchronizerStages(tr.Destination, tr.ClockDomain, flopConsumers, combReadSignals, signals)
                            : 0;
                        bool synchronized = syncStages >= 2;

                        crossings.Add(new CdcCrossingInfo(
                            "CDC", launch, launchClk, tr.Destination, tr.ClockDomain, width, synchronized, syncStages, isFalsePath, tr.Context));

                        if (!synchronized && !isFalsePath)
                        {
                            string detail = width > 1
                                ? $"Unsynchronized {width}-bit multi-bit bus CDC crossing from '{launch}' (clock '{launchClk}') to '{tr.Destination}' (clock '{tr.ClockDomain}'); multi-bit buses require Gray coding, handshake, or async FIFO."
                                : !isDirectFlopRead
                                    ? $"Combinational logic detected on CDC path from '{launch}' (clock '{launchClk}') to '{tr.Destination}' (clock '{tr.ClockDomain}'); register before crossing and add a 2-FF synchronizer."
                                    : $"Unsynchronized CDC crossing from '{launch}' (clock '{launchClk}') to '{tr.Destination}' (clock '{tr.ClockDomain}'); add a 2-FF synchronizer or SDC false-path.";
                            diagnostics.Add(new LintDiagnostic("CDCUNSYNC", LintSeverity.Warning, detail, "cdc", new LintLocation(sourceFile, null, null, tr.Destination, tr.Context)));
                        }
                    }

                    // RDC check: launch reset domain != capture reset domain (when both have explicit distinct resets)
                    if (flopReset.TryGetValue(launch, out string? launchRst) &&
                        tr.ResetDomain is { Length: > 0 } capRst &&
                        !launchRst.Equals(capRst, StringComparison.Ordinal))
                    {
                        string rKey = $"RDC|{launch}|{launchRst}|{tr.Destination}|{capRst}";
                        if (!seenCrossing.Add(rKey)) continue;

                        bool isFalsePath = effectiveSdc.IsFalsePath(launch, launchRst, tr.Destination, capRst);
                        crossings.Add(new CdcCrossingInfo(
                            "RDC", launch, launchRst, tr.Destination, capRst, width, Synchronized: false, SynchronizerStages: 0, isFalsePath, tr.Context));

                        if (!isFalsePath)
                        {
                            diagnostics.Add(new LintDiagnostic(
                                "RDCUNSYNC",
                                LintSeverity.Warning,
                                $"Reset domain crossing (RDC) from '{launch}' (reset '{launchRst}') to '{tr.Destination}' (reset '{capRst}'); asynchronous assertion of '{launchRst}' can cause metastability in '{tr.Destination}'.",
                                "cdc",
                                new LintLocation(sourceFile, null, null, tr.Destination, tr.Context)));
                        }
                    }
                }
            }
        }

        var domainInfos = detectedClocks.Order(StringComparer.Ordinal)
            .Select(clk => new ClockDomainInfo(
                clk,
                signals.TryGetValue(clk, out var info) && info.Direction == "input",
                effectiveSdc.HasClockTarget(clk),
                domainSignals.TryGetValue(clk, out var ds) ? ds.Order(StringComparer.Ordinal).ToArray() : []))
            .ToArray();

        return new CdcAnalysisResult(
            domainInfos,
            detectedResets.Order(StringComparer.Ordinal).ToArray(),
            crossings.AsReadOnly(),
            diagnostics.AsReadOnly());
    }

    private static int CountSynchronizerStages(
        string stage1Flop,
        string destClock,
        Dictionary<string, List<SeqTransfer>> flopConsumers,
        HashSet<string> combReadSignals,
        IReadOnlyDictionary<string, (int Width, string Direction)> signals)
    {
        // Stage 1 must be an internal flop (not directly exposed as output or read by combinational logic)
        if (combReadSignals.Contains(stage1Flop)) return 1;
        if (signals.TryGetValue(stage1Flop, out var s1Info) && s1Info.Direction == "output") return 1;

        int stages = 1;
        string cur = stage1Flop;
        for (int depth = 0; depth < 8; depth++)
        {
            if (!flopConsumers.TryGetValue(cur, out var consumers) || consumers.Count != 1)
                break;
            var next = consumers[0];
            if (next.ClockDomain != destClock || next.DirectSourceRef != cur)
                break;
            stages++;
            cur = next.Destination;
            if (stages >= 2) break;
        }
        return stages;
    }

    private static IEnumerable<(JsonElement Proc, string Context)> EnumerateProcesses(JsonElement bodyEl)
    {
        if (TryString(bodyEl, "kind") == "parallel" && bodyEl.TryGetProperty("items", out var items) && items.ValueKind == JsonValueKind.Array)
        {
            int i = 0;
            foreach (var it in items.EnumerateArray()) yield return (it, $"process[{i++}]");
        }
        else
        {
            yield return (bodyEl, "body");
        }
    }

    private static string? TryDetectSyncReset(JsonElement stmt)
    {
        JsonElement inner = stmt;
        while (TryString(inner, "kind") == "block" && inner.TryGetProperty("items", out var items) &&
               items.ValueKind == JsonValueKind.Array && items.GetArrayLength() == 1)
            inner = items[0];

        if (TryString(inner, "kind") != "if" || !inner.TryGetProperty("condition", out var cond) || !inner.TryGetProperty("then", out var thenEl))
            return null;

        // Check if 'then' only assigns constants
        if (!IsAllConstAssigns(thenEl, 0)) return null;

        if (TryString(cond, "kind") == "ref") return TryString(cond, "name");
        if (TryString(cond, "kind") is "not" or "bitnot" && cond.TryGetProperty("args", out var args) &&
            args.ValueKind == JsonValueKind.Array && args.GetArrayLength() == 1 && TryString(args[0], "kind") == "ref")
            return TryString(args[0], "name");
        return null;
    }

    private static bool IsAllConstAssigns(JsonElement stmt, int depth)
    {
        if (depth > MaxDepth || stmt.ValueKind != JsonValueKind.Object) return false;
        string? kind = TryString(stmt, "kind");
        if (kind == "block" && stmt.TryGetProperty("items", out var items) && items.ValueKind == JsonValueKind.Array && items.GetArrayLength() > 0)
        {
            foreach (var it in items.EnumerateArray())
                if (!IsAllConstAssigns(it, depth + 1)) return false;
            return true;
        }
        return kind is "nba" or "blocking" && stmt.TryGetProperty("value", out var v) && TryString(v, "kind") == "const";
    }

    private static void CollectSequentialTransfers(
        JsonElement stmt,
        string clockDomain,
        string? resetDomain,
        string context,
        List<SeqTransfer> transfers,
        int depth)
    {
        if (depth > MaxDepth || stmt.ValueKind != JsonValueKind.Object) return;
        string? kind = TryString(stmt, "kind");
        switch (kind)
        {
            case "block":
                if (stmt.TryGetProperty("items", out var items) && items.ValueKind == JsonValueKind.Array)
                    foreach (var it in items.EnumerateArray())
                        CollectSequentialTransfers(it, clockDomain, resetDomain, context, transfers, depth + 1);
                break;
            case "nba":
            case "blocking":
                if (stmt.TryGetProperty("target", out var tgt) && stmt.TryGetProperty("value", out var val))
                {
                    var reads = new HashSet<string>(StringComparer.Ordinal);
                    CollectExprRefs(val, reads, 0);
                    string? directRef = TryString(val, "kind") == "ref" ? TryString(val, "name") : null;
                    foreach (string dst in TargetOwners(tgt))
                        transfers.Add(new SeqTransfer(dst, clockDomain, resetDomain, directRef, reads, context));
                }
                break;
            case "if":
                if (stmt.TryGetProperty("then", out var t)) CollectSequentialTransfers(t, clockDomain, resetDomain, context, transfers, depth + 1);
                if (stmt.TryGetProperty("else", out var e)) CollectSequentialTransfers(e, clockDomain, resetDomain, context, transfers, depth + 1);
                break;
            case "case":
                if (stmt.TryGetProperty("items", out var ci) && ci.ValueKind == JsonValueKind.Array)
                    foreach (var it in ci.EnumerateArray())
                        if (it.TryGetProperty("body", out var b))
                            CollectSequentialTransfers(b, clockDomain, resetDomain, context, transfers, depth + 1);
                break;
            case "while":
            case "do":
            case "repeat":
            case "runtime_repeat":
            case "for":
                if (stmt.TryGetProperty("body", out var lb))
                    CollectSequentialTransfers(lb, clockDomain, resetDomain, context, transfers, depth + 1);
                break;
        }
    }

    private static void CollectTimedEventClocks(JsonElement stmt, string context, HashSet<string> clocks, HashSet<string> asyncResets, int depth)
    {
        if (depth > MaxDepth || stmt.ValueKind != JsonValueKind.Object) return;
        string? kind = TryString(stmt, "kind");
        if (kind == "event" && stmt.TryGetProperty("events", out var evs) && evs.ValueKind == JsonValueKind.Array)
        {
            var edgeSigs = new List<string>();
            foreach (var ev in evs.EnumerateArray())
            {
                string? edge = TryString(ev, "edge");
                if (edge is "posedge" or "negedge" && TryString(ev, "signal") is { Length: > 0 } s)
                    edgeSigs.Add(s);
            }
            if (edgeSigs.Count > 0) clocks.Add(edgeSigs[0]);
            for (int i = 1; i < edgeSigs.Count; i++) asyncResets.Add(edgeSigs[i]);
        }
        if (stmt.TryGetProperty("items", out var items) && items.ValueKind == JsonValueKind.Array)
            foreach (var it in items.EnumerateArray()) CollectTimedEventClocks(it, context, clocks, asyncResets, depth + 1);
        foreach (string f in new[] { "body", "then", "else" })
            if (stmt.TryGetProperty(f, out var ch)) CollectTimedEventClocks(ch, context, clocks, asyncResets, depth + 1);
    }

    private static void CollectCombinationalDependencies(JsonElement root, Dictionary<string, HashSet<string>> deps)
    {
        if (root.TryGetProperty("continuous", out var contEl) && contEl.ValueKind == JsonValueKind.Array)
        {
            foreach (var assign in contEl.EnumerateArray())
            {
                if (assign.ValueKind != JsonValueKind.Object ||
                    !assign.TryGetProperty("target", out var tgt) ||
                    !assign.TryGetProperty("value", out var val)) continue;
                var reads = new HashSet<string>(StringComparer.Ordinal);
                CollectExprRefs(val, reads, 0);
                foreach (string w in TargetOwners(tgt))
                {
                    if (!deps.TryGetValue(w, out var set)) { set = new HashSet<string>(StringComparer.Ordinal); deps[w] = set; }
                    set.UnionWith(reads);
                }
            }
        }
        if (root.TryGetProperty("combinational", out var combEl) && combEl.ValueKind == JsonValueKind.Array)
        {
            foreach (var block in combEl.EnumerateArray())
            {
                var reads = new HashSet<string>(StringComparer.Ordinal);
                var writes = new HashSet<string>(StringComparer.Ordinal);
                CollectStmtDeps(block, reads, writes, 0);
                foreach (string w in writes)
                {
                    if (!deps.TryGetValue(w, out var set)) { set = new HashSet<string>(StringComparer.Ordinal); deps[w] = set; }
                    set.UnionWith(reads);
                }
            }
        }
    }

    private static void CollectStmtDeps(JsonElement stmt, HashSet<string> reads, HashSet<string> writes, int depth)
    {
        if (depth > MaxDepth || stmt.ValueKind != JsonValueKind.Object) return;
        string? kind = TryString(stmt, "kind");
        if (stmt.TryGetProperty("condition", out var c)) CollectExprRefs(c, reads, 0);
        if (stmt.TryGetProperty("value", out var v)) CollectExprRefs(v, reads, 0);
        if (kind is "blocking" or "nba" && stmt.TryGetProperty("target", out var t))
            foreach (string w in TargetOwners(t)) writes.Add(w);
        if (stmt.TryGetProperty("items", out var items) && items.ValueKind == JsonValueKind.Array)
        {
            foreach (var it in items.EnumerateArray())
            {
                if (kind == "case" && it.TryGetProperty("body", out var cb)) CollectStmtDeps(cb, reads, writes, depth + 1);
                else CollectStmtDeps(it, reads, writes, depth + 1);
            }
        }
        foreach (string f in new[] { "body", "then", "else" })
            if (stmt.TryGetProperty(f, out var ch)) CollectStmtDeps(ch, reads, writes, depth + 1);
    }

    private static IEnumerable<string> TargetOwners(JsonElement target)
    {
        if (target.ValueKind != JsonValueKind.Object) yield break;
        string? kind = TryString(target, "kind");
        if (kind == "concat" && target.TryGetProperty("args", out var args) && args.ValueKind == JsonValueKind.Array)
        {
            foreach (var ch in args.EnumerateArray())
                foreach (string o in TargetOwners(ch)) yield return o;
        }
        else if (kind is "ref" or "index")
        {
            if (TryString(target, "name") is { Length: > 0 } n) yield return n;
        }
        else if (kind is "bitselect" or "partselect" or "indexedselect" && target.TryGetProperty("value", out var iv))
        {
            if (TryString(iv, "name") is { Length: > 0 } n) yield return n;
        }
    }

    private static void CollectExprRefs(JsonElement expr, HashSet<string> refs, int depth)
    {
        if (depth > MaxDepth || expr.ValueKind != JsonValueKind.Object) return;
        string? kind = TryString(expr, "kind");
        if (kind is "ref" or "size") { if (TryString(expr, "name") is { Length: > 0 } n) refs.Add(n); }
        else if (kind is "past" or "rose" or "fell" or "stable") { if (TryString(expr, "signal") is { Length: > 0 } s) refs.Add(s); }
        else if (kind is "index" or "exists")
        {
            if (TryString(expr, "name") is { Length: > 0 } m) refs.Add(m);
            if (expr.TryGetProperty("index", out var idx)) CollectExprRefs(idx, refs, depth + 1);
        }
        else if (kind is "bitselect" or "partselect" or "indexedselect" or "convert")
        {
            if (expr.TryGetProperty("value", out var v)) CollectExprRefs(v, refs, depth + 1);
            if (expr.TryGetProperty("index", out var i)) CollectExprRefs(i, refs, depth + 1);
            if (expr.TryGetProperty("base", out var b)) CollectExprRefs(b, refs, depth + 1);
        }
        else if (expr.TryGetProperty("args", out var args) && args.ValueKind == JsonValueKind.Array)
        {
            foreach (var a in args.EnumerateArray()) CollectExprRefs(a, refs, depth + 1);
        }
    }

    private static string? TryString(JsonElement el, string prop) =>
        el.ValueKind == JsonValueKind.Object && el.TryGetProperty(prop, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString() : null;
}
